const assert=require('node:assert/strict');
const L=require('../assets/lesson-ledger.js');
const now=new Date(2026,10,14,18).getTime();
const student={uid:'nikita',lessonPrice:300};
const lessons=[{id:'one',studentUid:'nikita',date:'2026-11-14',time:'12:00',durationMinutes:60,topic:'Алгебра',lessonPrice:300},{id:'two',studentUid:'nikita',date:'2026-11-15',time:'12:00',durationMinutes:60,topic:'Геометрия',lessonPrice:300}];
let rows=L.history(student,lessons,now);
assert.equal(rows.length,1);assert.equal(rows[0].paid,false);assert.equal(rows[0].amount,300);
assert.deepEqual(L.totals([student],lessons,now),{forecast:600,paid:0,unpaid:300,unpriced:0});
student.lessonHistory={[rows[0].id]:{...rows[0],paid:true}};
assert.equal(L.history(student,lessons,now).length,1,'Persisted automatic history must not duplicate');
assert.equal(L.totals([student],lessons,now).paid,300);
student.lessonPrice=900;
assert.equal(L.totals([student],lessons,now).paid,300,'Price changes must preserve the recorded amount');
student.lessonHistory[rows[0].id].voided=true;lessons[0].cancelled=true;
assert.equal(L.history(student,lessons,now).length,0,'Deleted history must not reappear');
assert.deepEqual(L.totals([student],lessons,now),{forecast:300,paid:0,unpaid:0,unpriced:0});
const other={uid:'other',lessonPrice:700,lessonHistory:{manual:{date:'2026-10-01',time:'12:00',amount:700,paid:true}}};
assert.equal(L.totals([student,other],lessons,now).paid,700);
assert.equal(L.totals([student,other],lessons,now).forecast,300,'Past-month payments must not inflate this month forecast');
const free={uid:'free',lessonPrice:0,lessonHistory:{a:{date:'2026-11-01',time:'12:00',amount:0,paid:true}}};
assert.equal(L.totals([free],[],now).paid,0,'Zero price is valid, never replaced by a default price');
assert.equal(L.price({subscriptionPrice:4800}),null,'Legacy package prices must not be invented as per-lesson prices');
const old={uid:'nikita',lessonPrice:300,lessonHistory:{legacy:{date:lessons[0].date,time:lessons[0].time,topic:lessons[0].topic,paid:true}}};
assert.equal(L.history(old,[{...lessons[0],cancelled:false}],now).length,1);
assert.equal(L.history({uid:'nikita'},[{...lessons[0],time:'17:30',cancelled:false}],now).length,0,'A 60-minute lesson at 17:30 is not complete at 18:00');
console.log('PASS: 300-ruble lesson, manual payment, different prices, month forecast, fixed historical amounts, cancellation, idempotence and duration');
